// 画面が score_max（その子の1日の最大点）を使うときの、2つの取り決め（純関数）。
//
// score_max は API が出す値で、採点区分が空だとその区分は0点固定・ボーナスも付かないため
// 100 + チャレンジ×25 より小さくなる（片方空なら50、両方空なら0）。ここを素通しすると、
// 分母が実態と合わなかったり 0除算になったりする。

/** 基本点（せいかつ＋しゅくだい）の満点。チャレンジ解放前の「◯点 / △点」の △ に出す。
 *
 *  ボーナスは基本点が満点の日にしか付かないので、score_max が100未満ならそれ自体が
 *  ボーナス抜きの満点＝min で取り出せる。しゅくだいが空の子に「50点 / 100点」と出して、
 *  全部やったのに半分に見える、を防ぐ（100 は せいかつ50＋しゅくだい50。採点の配点そのもので、
 *  真実源はバックエンドの judge.HABITS_MAX + DAILY_MAX）。 */
export function baseScoreMax(scoreMax: number): number {
	return Math.min(scoreMax, 100);
}

/** グラフの縦軸に使う分母。
 *
 *  両方の区分が空だと score_max は0になる。記録は項目を消しても残るので、その日の total は
 *  null ではなく0で届く＝`0 / 0` が NaN になり、SVG の座標が壊れて折れ線ごと消える。
 *  意味としての最大点は0のままにして、描画の分母だけ1に持ち上げる。 */
export function chartScoreMax(scoreMax: number): number {
	return Math.max(1, scoreMax);
}
